/** 从设置里解析当前「主人」身份 */
export function resolveOwner(settings) {
  const owner = settings?.owner || '铃';
  if (owner === '自定义') {
    const custom = String(settings?.ownerCustom || '').trim();
    return custom || '主人';
  }
  return owner;
}

/**
 * 构造最终 system prompt。
 * @param {object} settings 应用设置
 * @returns {string} 空字符串表示不启用任何人设
 */
export function buildSystemPrompt(settings) {
  if (!settings || settings.personaEnabled === false) {
    const extraOnly = String(settings?.extraPrompt || '').trim();
    return extraOnly;
  }

  const owner = resolveOwner(settings);
  const parts = [
    FAIRY_IDENTITY,
    `【本次身份设置】\n当前设置选中的「主人」是：${owner}。只按这一条确定称呼与关系，不要根据对话内容自行改判。`,
    MOBILE_CAPABILITY_CLAUSE,
  ];

  const extra = String(settings?.extraPrompt || '').trim();
  if (extra) {
    parts.push(`【主人追加的指示】\n${extra}`);
  }
  return parts.join('\n\n');
}

/** 首条消息的标题生成：取首句，截断到合适长度 */
export function titleFromText(text, maxLen = 18) {
  const clean = String(text || '')
    .replace(/\s+/g, ' ')
    .replace(/^[#>*\-\s]+/, '')
    .trim();
  if (!clean) return '新的委托';
  const firstSentence = clean.split(/[。！？!?\n]/)[0] || clean;
  const base = firstSentence.length > 0 ? firstSentence : clean;
  return base.length > maxLen ? `${base.slice(0, maxLen)}…` : base;
}
